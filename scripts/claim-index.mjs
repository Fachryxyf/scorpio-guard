/**
 * Which design claims are backed by a test, and which are only written down. M1.8.
 *
 * `DECISIONS.md` is the design record, and the tests name the decision they lock in
 * in their titles. Nothing enforced that pairing, so a decision could be edited while
 * the test that was supposed to notice kept passing, or a claim could be recorded and
 * never exercised at all. Both are the same hole: a reader cannot tell which half of
 * the document is machine-checked.
 *
 * This walks the decisions, finds which test files name each one, and writes the result
 * to `docs/CLAIMS.md`. A decision with no test target is not automatically a defect:
 * many of them are arguments about naming, scope, or rejected alternatives, which no
 * test can hold. So each one needs a written reason in `docs/CLAIMS-NOTES.md`, and the
 * check fails when a prose-only decision has neither.
 *
 * `--check` fails when the committed file is stale, so the index cannot drift from the
 * sources it describes.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUTPUT = 'docs/CLAIMS.md';
const NOTES = 'docs/CLAIMS-NOTES.md';
const TEST_ROOTS = ['src', 'examples'];
const ID = 'D[0-9]+[a-z]?(?:\\.[0-9]+)?';

function testFiles(directory) {
  const found = [];
  for (const entry of readdirSync(directory, { withFileTypes: true, recursive: true })) {
    if (!entry.isFile()) continue;
    const path = join(entry.parentPath ?? entry.path ?? directory, entry.name);
    if (path.endsWith('.test.ts')) found.push(path);
  }
  return found.sort();
}

function decisions() {
  const text = readFileSync('DECISIONS.md', 'utf8');
  const found = [];
  for (const match of text.matchAll(new RegExp('^## (' + ID + '): (.+)$', 'gm'))) {
    found.push({ id: match[1], title: match[2].trim() });
  }
  return found;
}

function reasons() {
  const map = new Map();
  if (!existsSync(NOTES)) return map;
  for (const match of readFileSync(NOTES, 'utf8').matchAll(new RegExp('^- (' + ID + '): (.+)$', 'gm'))) {
    map.set(match[1], match[2].trim());
  }
  return map;
}

function mentions(text, id) {
  // D1 must not match D10 or D1.1.
  const pattern = new RegExp('(?<![0-9A-Za-z.])' + id.replace('.', '\\.') + '(?![0-9])');
  return pattern.test(text);
}

const files = TEST_ROOTS.flatMap((root) => (existsSync(root) ? testFiles(root) : []));
const sources = files.map((path) => ({ path, text: readFileSync(path, 'utf8') }));
const explained = reasons();

const rows = decisions().map((decision) => ({
  ...decision,
  targets: sources.filter((source) => mentions(source.text, decision.id)).map((source) => source.path),
  note: explained.get(decision.id),
}));

const tested = rows.filter((row) => row.targets.length > 0);
const prose = rows.filter((row) => row.targets.length === 0);
const explainedOnly = prose.filter((row) => row.note);
const unexplained = prose.filter((row) => !row.note);
// A reason for a decision that now has a test has become an excuse: fail on it so
// the notes stay a description of the present rather than a sediment of the past.
const stale = tested.filter((row) => row.note);

function targetsLabel(targets) {
  const shown = targets.slice(0, 2).map((path) => '`' + path + '`').join(', ');
  return targets.length > 2 ? shown + ', +' + (targets.length - 2) : shown;
}

const lines = [
  '# Claim Index',
  '',
  'Generated by `npm run claims` from `DECISIONS.md`, the test files, and the reasons in',
  '`docs/CLAIMS-NOTES.md`. Do not edit by hand: `npm run check:claims` fails when this',
  'file is stale, and when a decision has neither a test nor a reason.',
  '',
  'A decision counts as backed when a test file names it. That is weaker than the test',
  'proving it and stronger than nothing: it means every design claim either has a place',
  'in the suite that would notice a change, or a written explanation of why it cannot',
  'have one.',
  '',
  'Total: ' + rows.length + ' decisions, ' + tested.length + ' named by a test, ' +
    explainedOnly.length + ' explained, ' + unexplained.length + ' unexplained.',
  '',
  '| Decision | Title | Tests |',
  '|---|---|---|',
  ...rows
    .filter((row) => row.targets.length > 0)
    .map((row) => '| ' + row.id + ' | ' + row.title.replace(/\|/g, '\\|') + ' | ' + targetsLabel(row.targets) + ' |'),
  '',
  '## Prose only, with the reason',
  '',
  'No test names these. Each reason says why a test cannot, and where the behaviour is',
  'covered instead when it is covered at all.',
  '',
  ...(explainedOnly.length === 0
    ? ['None.']
    : explainedOnly.map((row) => '- ' + row.id + ': ' + row.title + '. ' + row.note)),
  '',
  '## Prose only, and not yet explained',
  '',
  ...(unexplained.length === 0
    ? ['None.']
    : unexplained.map((row) => '- ' + row.id + ': ' + row.title)),
  '',
];

const generated = lines.join('\n');

if (process.argv.includes('--check')) {
  if (stale.length > 0) {
    for (const row of stale) {
      console.error('check-claims: ' + row.id + ' now has a test, remove its reason from ' + NOTES);
    }
    process.exit(1);
  }
  if (unexplained.length > 0) {
    for (const row of unexplained) {
      console.error('check-claims: ' + row.id + ' has no test and no reason in ' + NOTES);
    }
    process.exit(1);
  }
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current !== generated) {
    console.error('check-claims: ' + OUTPUT + ' is stale, run npm run claims');
    process.exit(1);
  }
  console.log(
    'claims ok: ' + rows.length + ' decisions, ' + tested.length + ' tested, ' + explainedOnly.length + ' explained in prose',
  );
} else {
  writeFileSync(OUTPUT, generated);
  console.log(
    'claims: ' + rows.length + ' decisions, ' + tested.length + ' tested, ' + explainedOnly.length + ' explained, ' +
      unexplained.length + ' unexplained, written to ' + OUTPUT,
  );
}
